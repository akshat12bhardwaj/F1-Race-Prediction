def scenario_matrix(df, columns=None):
    """Scenario feature matrix from raw columns (identical for training rows and custom entries)."""
    columns = columns or SCENARIO_FEATURES
    g = (df["grid_position"] if "grid_position" in df else pd.Series(np.nan, index=df.index)).astype(float)
    lg = np.log(g)
    pole_rate = df.get("circuit_pole_win_rate", pd.Series(np.nan, index=df.index)).fillna(DEFAULT_POLE_RATE)
    wet = df.get("wx_prestart_wet", pd.Series(np.nan, index=df.index)).fillna(0)
    wx = {k: df[k].astype(float).fillna(v) if k in df else pd.Series(v, index=df.index) for k, v in WX_RAW.items()}
    rain = np.log1p(wx["wx_prestart_precip_sum_mm"])
    num = lambda c: df[c].astype(float) if c in df else pd.Series(np.nan, index=df.index)
    weather = {   # race-level conditions and their interactions with grid, driver skill and car (D-033)
        "rain_log": rain, "air_temp_c": wx["wx_prestart_temp_mean_c"], "humidity_pct": wx["wx_prestart_humidity_mean_pct"],
        "wind_kmh": wx["wx_prestart_wind_speed_mean_kmh"], "log_grid_x_rain": lg * rain,
        "rain_x_race_skill": rain * num("net_race_skill"), "rain_x_car_pace": rain * num("constructor_last5_avg_finish_pct"),
        "heat_x_car_dnf": (wx["wx_prestart_temp_mean_c"] - 21.1) * num("constructor_dnf_rate_last10"),
        "wind_x_car_pace": wx["wx_prestart_wind_speed_mean_kmh"] * num("constructor_last5_avg_finish_pct")}
    out = pd.DataFrame({
        "log_grid": lg, "front_row": (g <= 2).astype(float).where(g.notna()),
        "pole": (g == 1).astype(float).where(g.notna()),
        "log_grid_x_pole_rate": lg * pole_rate, "log_grid_x_wet": lg * wet,
        "log_driver_career_starts": np.log1p(df["driver_career_starts"].astype(float)),
        "log_driver_circuit_starts": np.log1p(df["driver_circuit_starts"].astype(float)),
        **{k: v for k, v in weather.items() if k in columns},
    }, index=df.index)
    for c in columns:
        if c not in out:
            out[c] = df[c].astype(float)
    return out[columns]


# ---------------- Plackett-Luce ----------------
def _pad(X, race_ids, order_key):
    """Rows -> (R, M, d) padded array sorted by finishing order within race; mask (R, M)."""
    df = pd.DataFrame({"race": race_ids, "key": order_key, "i": np.arange(len(race_ids))})
    df = df.sort_values(["race", "key"], kind="mergesort")
    races = df["race"].unique()
    pos = df.groupby("race", sort=False).cumcount().to_numpy()
    r_idx = pd.Index(races).get_indexer(df["race"])
    M = pos.max() + 1
    Xp = np.zeros((len(races), M, X.shape[1]))
    mask = np.zeros((len(races), M), bool)
    Xp[r_idx, pos] = X[df["i"].to_numpy()]
    mask[r_idx, pos] = True
    return Xp, mask, races


def pl_loglik_grad(w, Xp, mask, race_w, alpha, top_k=None):
    """Mean negative PL log-likelihood over races (weighted) + L2; analytic gradient.
    top_k: truncated PL - only the first k picks enter the likelihood (the denominators still
    contain every remaining car), so the noisy order of the back of the field is ignored."""
    U = np.where(mask, Xp @ w, -np.inf)
    with np.errstate(invalid="ignore"):
        L = np.logaddexp.accumulate(U[:, ::-1], axis=1)[:, ::-1]      # L_k = logsumexp(U[k:])
    Lm = np.where(mask, L, 0.0)
    Um = np.where(mask, U, 0.0)
    M = U.shape[1]
    K = M if top_k is None else min(top_k, M)
    stage = np.arange(M) < K                                         # positions that enter the likelihood
    ll_r = ((Um - Lm) * stage).sum(axis=1)
    W = race_w / race_w.sum()
    loss = -(W * ll_r).sum() + 0.5 * alpha * w @ w
    # d ll / d u_i = [pos_i < K] - sum_{k <= pos_i, k < K} exp(u_i - L_k)
    tri = np.tril(np.ones((M, M), bool)) & stage[None, :]           # [i, k]: k <= i and k < K
    E = np.exp(np.where(tri[None] & mask[:, None, :] & mask[:, :, None],
                        Um[:, :, None] - Lm[:, None, :], -np.inf))
    G = np.where(mask, stage[None, :] - E.sum(axis=2), 0.0)
    grad = -np.einsum("r,rm,rmd->d", W, G, Xp) + alpha * w
    return loss, grad


class PlackettLuce(BaseEstimator):
    """Linear-utility Plackett-Luce, u = X w (no intercept: it cancels within a race)."""

    def __init__(self, alpha=1e-3, half_life_seasons=None, top_k=None):
        self.alpha, self.half_life_seasons, self.top_k = alpha, half_life_seasons, top_k

    def fit(self, X, race_ids, finish, seasons=None):
        X = np.asarray(X, float)
        Xp, mask, races = _pad(X, np.asarray(race_ids), np.asarray(finish, float))
        if self.half_life_seasons and seasons is not None:
            s = pd.Series(np.asarray(seasons)).groupby(np.asarray(race_ids)).first().reindex(races).to_numpy()
            race_w = 0.5 ** ((s.max() - s) / self.half_life_seasons)   # time weighting (Henderson & Kirrane)
        else:
            race_w = np.ones(len(races))
        res = minimize(pl_loglik_grad, np.zeros(X.shape[1]), args=(Xp, mask, race_w, self.alpha, self.top_k),
                       jac=True, method="L-BFGS-B", options={"maxiter": 500})
        self.coef_, self.n_iter_, self.converged_ = res.x, res.nit, res.success
        return self

    def utility(self, X):
        return np.asarray(X, float) @ self.coef_


class ScenarioRanker(BaseEstimator):
    """Preprocessing (median impute + missing indicators + scaling, fitted on training rows only)
    followed by a strength model, then Plackett-Luce over a race.

    kind = "pl_linear": linear PL on scenario features.
    kind = "hybrid_gbm": gradient boosting predicts finish percentile from scenario features;
           u = beta * (-prediction), with beta fitted by PL likelihood (1 parameter).
    kind = "pl_grid": linear PL on grid features only (baseline)."""

    def __init__(self, kind="pl_linear", alpha=1e-3, half_life_seasons=None, top_k=None, feature_set=None,
                 target="target_finish_position"):
        self.kind, self.alpha, self.half_life_seasons, self.top_k = kind, alpha, half_life_seasons, top_k
        self.feature_set, self.target = feature_set, target

    def _groups(self):
        if self.kind == "pl_grid":
            return FEATURE_SETS["grid_only"]
        return FEATURE_SETS[getattr(self, "feature_set", None) or "v1"]   # models saved before v2 lack the attribute

    def _cols(self):
        return [f for g in self._groups().values() for f in g]

    def fit(self, df):
        S = scenario_matrix(df, self._cols())
        self.prep_ = Pipeline([("impute", SimpleImputer(strategy="median", add_indicator=True)),
                               ("scale", StandardScaler())]).fit(S)
        Z = self.prep_.transform(S)
        if self.kind == "hybrid_gbm":
            self.gbm_ = HistGradientBoostingRegressor(max_iter=300, learning_rate=0.05, max_leaf_nodes=31,
                                                      min_samples_leaf=50, early_stopping=True,
                                                      random_state=SEED).fit(S, df["finish_pct"])
            Z = -self.gbm_.predict(S)[:, None]
        self.pl_ = PlackettLuce(self.alpha, self.half_life_seasons, self.top_k).fit(
            Z, df["race_id"], df[getattr(self, "target", "target_finish_position")], df["season"])
        return self

    def utility(self, df):
        S = scenario_matrix(df, self._cols())
        Z = -self.gbm_.predict(S)[:, None] if self.kind == "hybrid_gbm" else self.prep_.transform(S)
        return self.pl_.utility(Z)

    def contributions(self, df):
        """Exact additive utility decomposition by feature group (linear PL only), centred on the
        field mean so values read as 'advantage vs. this field'."""
        if self.kind != "pl_linear":
            return None
        S = scenario_matrix(df, self._cols())
        Z = self.prep_.transform(S)
        contrib = Z * self.pl_.coef_
        names = list(self.prep_.get_feature_names_out())
        out = {}
        for g, cols in self._groups().items():
            idx = [i for i, n in enumerate(names) if any(n == c or n == f"missingindicator_{c}" for c in cols)]
            v = contrib[:, idx].sum(axis=1)
            out[g] = v - v.mean()
        return pd.DataFrame(out, index=df.index)


# ---------------- race-level probabilities ----------------
def win_probs(u):
    e = np.exp(u - u.max())
    return e / e.sum()


def simulate_orders(u, n_sims=10000, seed=SEED):
    """Exact PL sampling via Gumbel-max. Returns (n_sims, N) array of finishing positions (1-based)."""
    rng = np.random.default_rng(seed)
    g = u[None, :] + rng.gumbel(size=(n_sims, len(u)))
    order = np.argsort(-g, axis=1)
    pos = np.empty_like(order)
    pos[np.arange(n_sims)[:, None], order] = np.arange(1, len(u) + 1)
    return pos


def race_probabilities(u, n_sims=10000, seed=SEED):
    """Win (exact), position distribution, podium/top-5 and expected position (Monte Carlo)."""
    pos = simulate_orders(u, n_sims, seed)
    N = len(u)
    dist = np.stack([(pos == k).mean(axis=0) for k in range(1, N + 1)], axis=1)   # (N drivers, N positions)
    return {"win": win_probs(u), "dist": dist, "podium": (pos <= min(3, N)).mean(axis=0),
            "top5": (pos <= min(5, N)).mean(axis=0), "expected": pos.mean(axis=0)}


def two_stage_simulation(race_model, quali_model, df, n_sims=5000, seed=SEED, fixed_grid=None):
    """Simulate qualifying then the race (D-021). Each simulated race first draws a grid order from the
    qualifying Plackett-Luce model, recomputes the race strengths for that grid, then draws the finishing
    order, so grid uncertainty propagates into the race result.
    Returns grid positions (n_sims, N), finishing positions (n_sims, N) and qualifying strengths."""
    rng = np.random.default_rng(seed)
    N = len(df)
    df = df.reset_index(drop=True)
    if fixed_grid is None:
        uq = quali_model.utility(df)
        grid = _positions(uq[None, :] + rng.gumbel(size=(n_sims, N)))
    else:
        uq = None
        grid = np.tile(np.asarray(fixed_grid, int), (n_sims, 1))
    # race strengths depend on the sampled grid: evaluate the race model on every (simulation, driver) row
    big = df.iloc[np.tile(np.arange(N), n_sims)].reset_index(drop=True)
    big["grid_position"] = grid.ravel().astype(float)
    u = race_model.utility(big).reshape(n_sims, N)
    pos = _positions(u + rng.gumbel(size=(n_sims, N)))
    return {"grid": grid, "pos": pos, "u_quali": uq}


def _positions(noisy):
    """Rank each row descending -> 1-based positions."""
    order = np.argsort(-noisy, axis=1)
    pos = np.empty_like(order)
    pos[np.arange(noisy.shape[0])[:, None], order] = np.arange(1, noisy.shape[1] + 1)
    return pos


def summarize_simulation(sim):
    pos, grid = sim["pos"], sim["grid"]
    N = pos.shape[1]
    return {"win": (pos == 1).mean(axis=0), "podium": (pos <= min(3, N)).mean(axis=0),
            "top5": (pos <= min(5, N)).mean(axis=0), "expected": pos.mean(axis=0),
            "dist": np.stack([(pos == k).mean(axis=0) for k in range(1, N + 1)], axis=1),
            "pole": (grid == 1).mean(axis=0), "expected_grid": grid.mean(axis=0)}
