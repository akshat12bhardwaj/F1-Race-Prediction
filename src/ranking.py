"""
Race-level ranking model for custom (hypothetical) races: Plackett-Luce (D-019).

Model: each car i in a race has a strength u_i = f(x_i). The finishing order is generated by
repeatedly picking the next finisher from the remaining cars with probability
exp(u_i) / sum_{j remaining} exp(u_j)  (Plackett 1975; Luce 1959).

Why this model for custom fields:
- Luce's choice axiom: the model restricted to ANY subset of cars is again Plackett-Luce with
  the same strengths, so one model fitted on real full fields gives coherent probabilities for
  an arbitrary hypothetical line-up of N drivers.
- Win probability is exact: softmax(u). Full finishing-order distributions are sampled exactly
  with the Gumbel-max trick: order = argsort(u + Gumbel noise) (Yellott 1977).
- The most probable single finishing order is the order of decreasing u.

Scenario features are built only from information a user can specify or that comes from a
driver/constructor performance snapshot, never from the real field of a race (no field size,
no grid percentile, no championship rank among race entrants, no qualifying times).
"""

