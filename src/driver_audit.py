"""
Driver data-coverage audit (read-only): the evidence behind every driver who started a race in the 2025 reference
season, and why each one is or is not in the app's prediction pool (simulate.reference_pool).

Per driver: race starts, classified finishes, qualifying results, races with a teammate (the basis of the car-neutral
skill rating), circuits raced, constructors and seasons, and how many of the models' driver-skill features are
missing for the 2025 driver-season.

Outputs: outputs/tables/driver_eligibility_audit.csv, docs/DRIVER_DATA_AUDIT.md
Run:     python -m src.driver_audit
"""

import pandas as pd

from src import simulate
from src.config import PROJECT_ROOT, load_config
from src.features import load_features


def main():
    D = simulate._data()
    mf = load_features()
    mates = mf.groupby(["race_id", "constructor_id"])["driver_id"].transform("size") >= 2
    ev = mf.assign(classified=mf["target_dnf"] == 0, quali=mf["qualifying_position"].notna(), mate=mates).groupby("driver_id").agg(
        starts=("race_id", "size"), classified=("classified", "sum"), quali_results=("quali", "sum"),
        teammate_races=("mate", "sum"), circuits=("circuit_id", "nunique"), first=("season", "min"), last=("season", "max"),
        constructors=("constructor_id", lambda s: ", ".join(dict.fromkeys(s))))
    pool = simulate.reference_pool()
    yr = pool["reference_season"]
    rows = []
    for status, ds in (("eligible", pool["eligible"]), ("excluded", pool["excluded"])):
        for d in ds:
            e = ev.loc[d["driver_id"]]
            rows.append({"driver": f"{d['first_name']} {d['last_name']}", "driver_id": d["driver_id"],
                         f"team_{yr}": d["constructor_name"], "status": status, "starts": int(e["starts"]),
                         f"starts_{yr}": d["season_starts"], "classified": int(e["classified"]),
                         "quali_results": int(e["quali_results"]), "teammate_races": int(e["teammate_races"]),
                         "circuits": int(e["circuits"]), "seasons": f"{e['first']}-{e['last']}", "constructors": e["constructors"],
                         "imputed_skill_features": d["imputed_skill_features"], "gaps": "; ".join(d.get("gaps", []))})
    out = pd.DataFrame(rows)
    tables = PROJECT_ROOT / load_config()["paths"]["tables"]
    out.to_csv(tables / "driver_eligibility_audit.csv", index=False)
    pol = pool["policy"]
    md = ["# Driver data-coverage audit", "",
          "Generated by `python -m src.driver_audit` (read-only). Full table: `outputs/tables/driver_eligibility_audit.csv`.", "",
          f"## Reference season: {yr}", "",
          f"The data ends in {yr}, so the app predicts with {yr} drivers in {yr} cars. Nothing from 2026 is used, and no "
          "driver without F1 records is shown with a guessed skill profile.", "",
          "## Evidence policy", "",
          "The course models read six driver-skill features: two teammate-network ratings (race and qualifying), three "
          "teammate-gap features over the last 10 races, and age. A driver is in the prediction pool only if:",
          f"- at least {pol['min_career_starts']} career starts (the gap features are 10-race windows),",
          f"- at least {pol['min_season_starts']} starts in {yr} (the form season the app uses),",
          "- all six skill features observed (no imputation of driver ability),",
          f"- a {yr} performance profile for their car.", "",
          "Circuit history is **not** required: the models impute a first visit from the training distribution, exactly as "
          "for any real driver's first race at a track.", "",
          f"## Result: {int((out['status'] == 'eligible').sum())} eligible, {int((out['status'] == 'excluded').sum())} excluded", "",
          "| Driver | Team | Status | Evidence | Gap |", "|---|---|---|---|---|"]
    for _, r in out.iterrows():
        md.append(f"| {r['driver']} | {r[f'team_{yr}']} | {r['status']} | {r['starts']} starts ({r[f'starts_{yr}']} in {yr}), "
                  f"{r['quali_results']} qualifying results, {r['teammate_races']} teammate races; "
                  f"{r['imputed_skill_features']}/6 skill features missing | {r['gaps'] or '—'} |")
    md += ["", "Excluded drivers are not replaced. The default grid is the eligible field in the seat each driver held at "
           f"the end of {yr}; a team may enter at most two cars."]
    (PROJECT_ROOT / "docs/DRIVER_DATA_AUDIT.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(out[["driver", "status", "starts", "quali_results", "teammate_races", "imputed_skill_features", "gaps"]].to_string(index=False))


if __name__ == "__main__":
    main()
